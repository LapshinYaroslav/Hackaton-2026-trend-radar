"""Закреплённая конфигурация модели. Меняется только сознательно и с пересчётом.

Шесть признаков, нормировка внутри области, порог из внутренней кросс-валидации.
Числа прогона, на котором конфигурация закреплена, лежат в отчёте
reports/model_release_*.md; заново они не пересчитываются.

ПЕРЕИМЕНОВАНИЕ. Признак share_market назывался «долей рыночных документов», но
считает он не это: n_news_wordmatch / (n_research + n_news_wordmatch), где числитель —
документы TechCrunch, найденные ПО СЛОВАМ названия, а не по точной фразе, а
знаменатель добавляет к ним научные публикации OpenAlex и arXiv. Измерено на полной
выдаче: точную фразу содержат 6.5 % найденных документов, все слова названия — 83 %.
Новое имя share_news_wordmatch говорит это прямо. Старое оставлено алиасом: им
подписаны собранные таблицы признаков и кэш, ломать их незачем.
"""
from __future__ import annotations

import numpy as np
import pandas as pd

MODEL_VERSION = "s2a1-v1"
CUTOFF_DATE = "2026-09-01"
SEED = 42

# Признак, ради которого всё переименование. Формула — в докстринге модуля.
NEWS_SHARE = "share_news_wordmatch"
# Старое имя -> новое. Читается при загрузке любой таблицы признаков.
ALIASES = {"share_market": NEWS_SHARE}

# Шесть признаков итоговой модели. Порядок фиксирован: в нём лежат коэффициенты.
FEATURES = ["volume", "growth_research", "recency", NEWS_SHARE, "share_prev6",
            "age_first_arxiv"]

# Нормировка: центр и масштаб считаются внутри области по обучающей части.
# Область, которой в обучении не было, нормируется общими центром и масштабом.
NORMALIZATION = "area_z"
MIN_AREA_ROWS = 4
# Что выбирает пользователь, когда его технология не из наших шести областей.
# Отдельной логики под это не нужно: любая незнакомая область уходит в откат на
# общие центр и масштаб. Константа нужна интерфейсу, чтобы показать один и тот же
# вариант всем, и отчётности, чтобы к нему привязать метрики режима отката.
OTHER_AREA = "другое"

# Кросс-валидация и подбор порога.
N_SPLITS = 5
N_REPEATS = 10
N_INNER_SPLITS = 4
THRESHOLD_GRID = np.round(np.arange(0.25, 0.7501, 0.025), 3)
THRESHOLD_CRITERION = "accuracy"

# Объяснение признака человеку: короткая строка на признак для выдачи.
EXPLANATIONS = {
    "volume": "объём документов о технологии",
    "growth_research": "рост научных публикаций против фона источника",
    "recency": "свежесть документов",
    NEWS_SHARE: "доля новостей, найденных по словам названия, среди всех документов",
    "share_prev6": "доля документов предыдущей шестилетки",
    "age_first_arxiv": "годы от первого препринта arXiv до даты среза",
}


def canonical(frame: pd.DataFrame) -> pd.DataFrame:
    """Переименовывает устаревшие колонки в канонические имена.

    Таблицы признаков, собранные до переименования, подписаны старым именем.
    Функция вызывается на входе обучения и предсказания, поэтому дальше по коду
    встречается только каноническое имя.
    """
    present = {old: new for old, new in ALIASES.items()
               if old in frame.columns and new not in frame.columns}
    return frame.rename(columns=present) if present else frame
